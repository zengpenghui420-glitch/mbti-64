function mulberry32(seed: number) {
  let state = seed;
  return () => {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(list: T[], seed: number): T[] {
  const rand = mulberry32(seed);
  const arr = [...list];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    const swap = arr[i];
    arr[i] = arr[j]!;
    arr[j] = swap!;
  }
  return arr;
}

const ORDER: Dimension[] = ["EI", "NS", "TF", "JP", "AT", "CH"];

function buildQuestions(): Question[] {
  const rows: Array<Omit<Question, "id">> = [];
  const count = GROUPS.EI.length;
  for (let i = 0; i < count; i += 1) {
    for (const dim of ORDER) {
      const item = GROUPS[dim][i];
      if (!item) continue;
      rows.push({ dim, pole: item[0], text: item[1] });
    }
  }
  return shuffle(rows, 20260518).map((row, index) => ({ ...row, id: index + 1 }));
}

export const QUESTIONS: Question[] = buildQuestions();
